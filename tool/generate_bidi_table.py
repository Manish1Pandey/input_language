#!/usr/bin/env python3
"""Generates lib/src/bidi_table.g.dart from Python's Unicode character database.

Run: python3 tool/generate_bidi_table.py > lib/src/bidi_table.g.dart

Strong classes (UAX #9): L -> left-to-right, R and AL -> right-to-left.
Unassigned code points get their DerivedBidiClass.txt default: R / AL inside the
right-to-left default blocks, BN for noncharacters and default-ignorables, ET for
the currency-symbol block, and L everywhere else.
"""
import sys
import unicodedata

R_DEFAULT = [(0x0590, 0x05FF), (0x07C0, 0x085F), (0xFB1D, 0xFB4F), (0x10800, 0x10CFF),
             (0x10D40, 0x10EBF), (0x10F00, 0x10F2F), (0x10F70, 0x10FFF), (0x1E800, 0x1EC6F),
             (0x1ECC0, 0x1ECFF), (0x1ED50, 0x1EDFF), (0x1EF00, 0x1EFFF)]
AL_DEFAULT = [(0x0600, 0x07BF), (0x0860, 0x08FF), (0xFB50, 0xFDCF), (0xFDF0, 0xFDFF),
              (0xFE70, 0xFEFF), (0x10D00, 0x10D3F), (0x10EC0, 0x10EFF), (0x10F30, 0x10F6F),
              (0x1EC70, 0x1ECBF), (0x1ED00, 0x1ED4F), (0x1EE00, 0x1EEFF)]
NEUTRAL_DEFAULT = [(0x20A0, 0x20CF), (0x2060, 0x206F), (0xFFF0, 0xFFF8), (0xE0000, 0xE0FFF),
                   (0xFDD0, 0xFDEF)]


def in_ranges(cp, ranges):
    return any(a <= cp <= b for a, b in ranges)


def direction(cp):
    ch = chr(cp)
    if unicodedata.category(ch) != 'Cn':
        cls = unicodedata.bidirectional(ch)
        if cls == 'L':
            return 0
        if cls in ('R', 'AL'):
            return 1
        return None
    if (cp & 0xFFFE) == 0xFFFE or in_ranges(cp, NEUTRAL_DEFAULT):
        return None
    if in_ranges(cp, R_DEFAULT) or in_ranges(cp, AL_DEFAULT):
        return 1
    if 0xD800 <= cp <= 0xDFFF:
        return None
    return 0


ranges = []
for cp in range(0x110000):
    d = direction(cp)
    if d is None:
        continue
    if ranges and ranges[-1][2] == d and ranges[-1][1] == cp - 1:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, d])

out = sys.stdout
out.write('// GENERATED FILE - DO NOT EDIT BY HAND.\n')
out.write('// Generated by tool/generate_bidi_table.py from the Unicode %s\n' % unicodedata.unidata_version)
out.write('// character database (Bidi_Class L, R, AL and DerivedBidiClass defaults).\n\n')
out.write('/// Unicode version the strong-direction table was generated from.\n')
out.write("const String kBidiUnicodeVersion = '%s';\n\n" % unicodedata.unidata_version)
out.write('/// Sorted, non-overlapping ranges of strong code points, as triples\n')
out.write('/// `start, end (inclusive), direction` where direction 0 = L and 1 = R/AL.\n')
out.write('const List<int> kStrongDirectionRanges = <int>[\n')
for a, b, d in ranges:
    out.write('  0x%X, 0x%X, %d,\n' % (a, b, d))
out.write('];\n')
sys.stderr.write('%d ranges\n' % len(ranges))
